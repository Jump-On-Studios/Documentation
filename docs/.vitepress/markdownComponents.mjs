// Renders the Vue components used in the Markdown pages to plain Markdown for
// the `.md` export, including the ones that load their content client side
// (ScriptConfig, charts...), which would otherwise be empty for LLMs.

import fs from "node:fs";
import path from "node:path";

const CONFIG_API = "https://jumpon-studios.com/api/scripts/config/";

const formatNumber = (n) => new Intl.NumberFormat("en-US").format(n);

function codeBlock(content, lang = "") {
  const longest = Math.max(
    2,
    ...(content.match(/`+/g) || []).map((m) => m.length),
  );
  const fence = "`".repeat(longest + 1);
  return `${fence}${lang}\n${content.replace(/\s+$/, "")}\n${fence}`;
}

function table(headers, rows) {
  return [
    `| ${headers.join(" | ")} |`,
    `| ${headers.map(() => "---").join(" | ")} |`,
    ...rows.map((r) => `| ${r.join(" | ")} |`),
  ].join("\n");
}

// --- <ScriptConfig scriptPath="..." /> -------------------------------------

const SCRIPT_CONFIG_RE = /<ScriptConfig\s+scriptPath="([^"]+)"\s*\/>/g;
const configCache = new Map();
// The build fetches the configs of every page at once: limit the concurrent
// requests and retry, as some connections get dropped otherwise.
const CONFIG_CONCURRENCY = 4;
const CONFIG_ATTEMPTS = 3;
let activeConfigRequests = 0;
const configQueue = [];

async function withConfigSlot(task) {
  if (activeConfigRequests >= CONFIG_CONCURRENCY) {
    await new Promise((resolve) => configQueue.push(resolve));
  }
  activeConfigRequests++;
  try {
    return await task();
  } finally {
    activeConfigRequests--;
    configQueue.shift()?.();
  }
}

async function requestConfig(scriptPath) {
  for (let attempt = 1; ; attempt++) {
    let retryable = true;
    try {
      const res = await fetch(CONFIG_API + scriptPath, {
        signal: AbortSignal.timeout(30000),
      });
      retryable = res.status >= 500 || res.status === 429;
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const data = await res.json();
      if (!data.success || !data.files?.length) {
        retryable = false;
        throw new Error("no files");
      }
      return data.files;
    } catch (e) {
      if (!retryable || attempt >= CONFIG_ATTEMPTS) throw e;
      await new Promise((resolve) => setTimeout(resolve, attempt * 2000));
    }
  }
}

export function fetchConfig(scriptPath) {
  if (!configCache.has(scriptPath)) {
    configCache.set(
      scriptPath,
      withConfigSlot(() => requestConfig(scriptPath)),
    );
  }
  return configCache.get(scriptPath);
}

// Mirrors the text of docs/.vitepress/theme/components/ScriptConfig.vue
function renderScriptConfig(files) {
  const scriptName = files[0].path.split("/")[0];
  const newFormat = files.some((f) => f.path.includes("_default.lock"));
  const intro = newFormat
    ? `The configuration files are located in the \`config\` folder within the resource. This folder contains two subfolders:

- **\`_default.lock/\`** - Contains the default configuration files. **Do not edit these files directly** as they may be overwritten during updates.
- **\`custom/\`** - This is where you place your custom configuration files to override the defaults.

### How to customize the configuration

1. Navigate to \`${scriptName}/config/_default.lock/\`
2. Copy the file you want to modify (e.g., \`prices.lua\`)
3. Paste it into \`${scriptName}/config/custom/\`
4. Edit the copied file in the \`custom\` folder

The script automatically loads files from \`custom/\` first, and only uses \`_default.lock/\` as a fallback. This system ensures your customizations are preserved when updating the script.

### Default configuration files`
    : `The configuration file is \`config.lua\` in the resource root. **Do not edit this file directly** as your changes may be lost during updates. Instead, use \`overwriteConfig.lua\` to store your customizations.

- **\`config.lua\`** - Default configuration maintained by developers. **Do not modify this file.**
- **\`overwriteConfig.lua\`** - This is where you place only the values you want to override.

### How to customize the configuration

1. Open \`${scriptName}/overwriteConfig.lua\`
2. Find the value you want to change in \`config.lua\` (e.g., \`Config.language\`)
3. Copy only that line into \`overwriteConfig.lua\`
4. Edit the copied value to your liking

The script loads \`config.lua\` first, then \`overwriteConfig.lua\` overwrites only the values you redefine. This ensures your customizations are preserved when updating the script.`;

  const blocks = files.map(
    (f) => `\`${f.path}\`\n\n${codeBlock(f.content, "lua")}`,
  );
  return [intro, ...blocks].join("\n\n");
}

export function scriptConfigPaths(body) {
  return [...new Set([...body.matchAll(SCRIPT_CONFIG_RE)].map((m) => m[1]))];
}

// transformPageData hook: fetches the config files of the <ScriptConfig>
// components of the page once at build time, read by ScriptConfig.vue.
export async function attachScriptConfigs(pageData, { siteConfig }) {
  if (pageData.isNotFound || !pageData.relativePath) return;
  const source = fs.readFileSync(
    path.join(siteConfig.srcDir, pageData.relativePath),
    "utf-8",
  );
  const paths = scriptConfigPaths(source);
  if (!paths.length) return;
  pageData.scriptConfigs = {};
  await Promise.all(
    paths.map(async (p) => {
      try {
        pageData.scriptConfigs[p] = await fetchConfig(p);
      } catch (e) {
        console.warn(`⚠ ScriptConfig "${p}" not loaded: ${e.message}`);
      }
    }),
  );
}

async function scriptConfig(body, { url }) {
  const paths = scriptConfigPaths(body);
  const rendered = {};
  await Promise.all(
    paths.map(async (p) => {
      try {
        rendered[p] = renderScriptConfig(await fetchConfig(p));
      } catch (e) {
        console.warn(`⚠ ScriptConfig "${p}" not exported: ${e.message}`);
        rendered[p] =
          `_The configuration files could not be loaded. See ${url}_`;
      }
    }),
  );
  return body.replace(SCRIPT_CONFIG_RE, (_, p) => rendered[p]);
}

// --- npc-clothes charts (loaded from /data/charts/*.json) ------------------

function chartSummary(publicDir, file) {
  const data = JSON.parse(
    fs.readFileSync(path.join(publicDir, "data/charts", file), "utf-8"),
  );
  const male = data.datasets.find((d) => d.label === "male").data;
  const female = data.datasets.find((d) => d.label === "female").data;
  const sum = (a) => a.reduce((x, y) => x + y, 0);
  const rows = data.labels
    .map((label, i) => [label, male[i], female[i]])
    .sort((a, b) => b[1] + b[2] - (a[1] + a[2]));
  return {
    male: sum(male),
    female: sum(female),
    total: sum(male) + sum(female),
    table: table(
      ["Category", "Male", "Female"],
      rows.map(([l, m, f]) => [l, formatNumber(m), formatNumber(f)]),
    ),
  };
}

function npcClothesCharts(body, { publicDir }) {
  if (!body.includes(':data="modelChartData"')) return body;
  const models = chartSummary(publicDir, "npc_clothes_no_mp_model.json");
  const variations = chartSummary(publicDir, "npc_category_no_mp.json");
  const values = {
    totalModels: models.total,
    totalMaleModels: models.male,
    totalFemaleModels: models.female,
    totalVariations: variations.total,
    totalMaleVariations: variations.male,
    totalFemaleVariations: variations.female,
  };
  return body
    .replace(
      /\{\{\s*Intl\.NumberFormat\(\)\.format\((\w+)\)\s*\}\}/g,
      (m, name) => (name in values ? formatNumber(values[name]) : m),
    )
    .replace(/<Chart\b[^>]*:data="modelChartData"[^>]*\/>/, models.table)
    .replace(
      /<Chart\b[^>]*:data="variationChartData"[^>]*\/>/,
      variations.table,
    );
}

// --- <InteriorGallery /> (data hardcoded in the component) -----------------

let interiorsTable;
function interiorGallery(body, { srcDir }) {
  if (!body.includes("<InteriorGallery")) return body;
  if (interiorsTable === undefined) {
    const vue = fs.readFileSync(
      path.join(srcDir, ".vitepress/theme/components/InteriorGallery.vue"),
      "utf-8",
    );
    const literal = vue.match(/const interiorsData = (\[[\s\S]*?\n\]);/)?.[1];
    const interiors = literal ? new Function(`return ${literal}`)() : [];
    interiorsTable = table(
      ["Interior ID", "Category", "Rooms", "Add-on"],
      interiors.map((i) => [`\`${i.id}\``, i.category, i.rooms, i.addon]),
    );
  }
  return body.replace(/<InteriorGallery\s*\/>/g, interiorsTable);
}

// --- Static components ------------------------------------------------------

function staticComponents(body, { url }) {
  return body
    .replace(/<Badge(Client|Server|Shared|Optional)\s*\/>/g, "`[$1]`")
    .replace(
      /<Badge\b[^>]*\btext="([^"]+)"[^>]*\/>/g,
      (_, text) => `\`[${text}]\``,
    )
    .replace(
      /<PriceGenerator\s*\/>/g,
      `_Interactive price generator, available at ${url}_`,
    );
}

// Top level <script> / <style> blocks are Vue code, not documentation
function stripVueBlocks(body) {
  return body.replace(/^<(script|style)\b[^>]*>[\s\S]*?^<\/\1>\s*$/gm, "");
}

export async function renderComponents(body, ctx) {
  body = stripVueBlocks(body);
  body = await scriptConfig(body, ctx);
  body = npcClothesCharts(body, ctx);
  body = interiorGallery(body, ctx);
  return staticComponents(body, ctx);
}
